//! Generate API, permission and settings TypeScript artifacts.
//!
//! The browser's types are not written by hand and not generated from the
//! Rust types directly: they are generated from the OpenAPI document, by
//! `openapi-typescript`, so that the document people read and the types
//! the browser compiles against cannot differ. After its output, every
//! schema is exported under its own name.

use serde_json::Value;
use std::path::Path;
use std::process::Command;

/// What went wrong, as a sentence.
pub type Failure = String;

/// Writes the TypeScript of the OpenAPI document at `openapi` to `out`,
/// with the generator installed in `frontend`.
pub fn api_types(
    frontend: &Path,
    openapi: &Path,
    document: &Value,
    out: &Path,
) -> Result<(), Failure> {
    let status = Command::new("npm")
        .args(["exec", "--offline", "--", "openapi-typescript"])
        .arg(openapi)
        .arg("--output")
        .arg(out)
        .args([
            "--root-types",
            "--root-types-no-schema-prefix",
            "--alphabetize",
        ])
        .current_dir(frontend)
        .status()
        .map_err(|error| format!("npm could not be run in {}: {error}", frontend.display()))?;
    if !status.success() {
        return Err(format!(
            "openapi-typescript failed ({status}); run `npm ci` in {} first",
            frontend.display()
        ));
    }
    let generated = std::fs::read_to_string(out)
        .map_err(|error| format!("cannot read {}: {error}", out.display()))?;
    let count = document["components"]["schemas"]
        .as_object()
        .map_or(0, serde_json::Map::len);
    let header = format!(
        "// Generated by `cargo xtask contracts` from docs/openapi.json ({count} types). Do not edit.\n/* eslint-disable */\n"
    );
    std::fs::write(out, header + &generated)
        .map_err(|error| format!("cannot write {}: {error}", out.display()))
}
