/** What an emoji is called, for a screen reader and for a list that names it: those of its words that are in Latin letters, the first three. */
export function emojiName([, words]: EmojiEntry): string {
  return words
    .split(' ')
    .filter((word) => /^[a-z]+$/.test(word))
    .slice(0, 3)
    .join(' ');
}

/** Every entry whose words hold all the words of `query`; the whole list of a group when the query is empty. */
export function findEmoji(query: string): readonly EmojiEntry[] {
  const wanted = query.trim().toLowerCase().split(/\s+/).filter((word) => word !== '');
  const all = EMOJI_GROUPS.flatMap((group) => EMOJI[group]);
  if (wanted.length === 0) return all;
  return all.filter(([, words]) => wanted.every((word) => words.includes(word)));
}
