//! Canonical UI catalogue fixture from the full internal contract document.
//! No route, verb or permission inference: copy the renderer's exact operation extensions.

use serde_json::Value;
use std::collections::BTreeMap;
use std::path::Path;

fn render(document: &Value) -> Result<(String, usize), String> {
    let paths = document["paths"]
        .as_object()
        .ok_or("the internal contract has no paths")?;
    let mut operations = BTreeMap::new();
    for methods in paths.values() {
        for operation in methods
            .as_object()
            .ok_or("invalid internal path methods")?
            .values()
        {
            if operation.get("operationId").is_none() {
                continue;
            }
            let metadata = operation
                .get("x-orch-operation")
                .filter(|value| value.is_object())
                .ok_or("an internal operation lacks its canonical metadata")?;
            let id = metadata["operation_id"]
                .as_str()
                .ok_or("canonical operation ID is missing")?;
            if operation["operationId"].as_str() != Some(id) {
                return Err(format!("canonical operation identity differs: {id}"));
            }
            if operations.insert(id.to_owned(), metadata.clone()).is_some() {
                return Err(format!("duplicate canonical operation ID: {id}"));
            }
        }
    }
    let mut kinds = Vec::new();
    for name in ["ObjectKind", "KeyIdentityKind"] {
        let entries = document["components"]["schemas"][name]["oneOf"]
            .as_array()
            .ok_or_else(|| format!("the internal contract has no {name} alternatives"))?;
        for entry in entries {
            kinds.push(
                entry["const"]
                    .as_str()
                    .ok_or_else(|| format!("{name} has a nonliteral target kind"))?,
            );
        }
    }
    let rows: Vec<Value> = operations.into_values().collect();
    let count = rows.len();
    let kinds = serde_json::to_string(&kinds).map_err(|error| error.to_string())?;
    let rows = serde_json::to_string_pretty(&rows).map_err(|error| error.to_string())?;
    Ok((
        format!(
            "/** Generated by `cargo xtask contracts` from full internal operation metadata.\n * Do not edit; `contracts --check` verifies the complete native catalogue fixture. No permission inference. */\nimport type {{ KeyTargetKind, Operation }} from '../../src/generated/api-types';\n\nexport const KEY_TARGET_KINDS: readonly KeyTargetKind[] = {kinds};\n\nexport const TOKEN_OPERATIONS: Operation[] = {rows};\n"
        ),
        count,
    ))
}

/// Writes every exact operation and target kind from the already-rendered full internal document.
pub fn write(path: &Path, document: &Value) -> Result<usize, String> {
    let (text, count) = render(document)?;
    std::fs::write(path, text)
        .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
    Ok(count)
}

#[cfg(test)]
#[allow(clippy::unwrap_used, reason = "generator controls fail by panicking")]
mod tests {
    use super::*;
    use serde_json::json;

    fn fixture() -> Value {
        json!({"paths":{
            "/login":{"post":{"operationId":"Login", "x-orch-operation":{"operation_id":"Login","delegation":"authentication_protocol","variants":[]}}},
            "/business":{"get":{"operationId":"Business", "x-orch-operation":{"operation_id":"Business","delegation":"business","variants":[]}}}
        },"components":{"schemas":{
            "ObjectKind":{"oneOf":[{"const":"org"}]},
            "KeyIdentityKind":{"oneOf":[{"const":"account"}]}
        }}})
    }

    #[test]
    fn full_fixture_preserves_nonbusiness_metadata_and_target_kinds() {
        let source = fixture();
        let (text, count) = render(&source).unwrap();
        assert_eq!(count, 2);
        let (_, rows) = text
            .split_once("export const TOKEN_OPERATIONS: Operation[] = ")
            .unwrap();
        let rows: Value = serde_json::from_str(rows.trim().trim_end_matches(';')).unwrap();
        assert_eq!(
            rows,
            json!([
                source["paths"]["/business"]["get"]["x-orch-operation"],
                source["paths"]["/login"]["post"]["x-orch-operation"]
            ])
        );
        assert!(
            text.contains("KEY_TARGET_KINDS: readonly KeyTargetKind[] = [\"org\",\"account\"]")
        );
    }

    #[test]
    fn missing_or_duplicate_metadata_cannot_silently_shrink_the_fixture() {
        let mut missing = fixture();
        missing["paths"]["/login"]["post"]
            .as_object_mut()
            .unwrap()
            .remove("x-orch-operation");
        assert!(render(&missing).is_err());
        let mut duplicate = fixture();
        duplicate["paths"]["/copy"] = duplicate["paths"]["/login"].clone();
        assert!(render(&duplicate).is_err());
    }
}
