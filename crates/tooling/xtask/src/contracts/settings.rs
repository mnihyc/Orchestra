//! Generate the build-local help registry from the same authored definitions the API serves.

use serde_json::{Value, json};
use std::path::Path;

/// The full registry with the help catalogue keys, independent of a live server.
pub fn data() -> Result<Value, String> {
    let mut rows = Vec::new();
    for def in orch_settings_contract::registry::all() {
        let mut row = serde_json::to_value(def).map_err(|error| format!("{}: {error}", def.key))?;
        row["text_key"] = json!(format!("day100.builtin.{}", def.key));
        row["keywords"] = json!([]);
        if let orch_settings_contract::registry::Schema::Int { unit, .. } = def.schema {
            let unit = if unit == orch_settings_contract::registry::Unit::Count {
                "raw"
            } else {
                unit.as_str()
            };
            row["display"] = json!({ "unit": unit, "zero": def.zero_disables().then_some("off") });
        }
        rows.push(row);
    }
    Ok(Value::Array(rows))
}

/// Writes one generated TypeScript artifact; the integrator invokes this through contracts.
pub fn write(out: &Path) -> Result<(), String> {
    let rows = serde_json::to_string_pretty(&data()?).map_err(|error| error.to_string())?;
    let text = format!(
        "// Generated by cargo xtask contracts. Do not edit.\n/* eslint-disable */\nimport type {{ SettingDef }} from './api-types';\n\nexport const SETTINGS_REGISTRY: readonly SettingDef[] = {rows};\n"
    );
    std::fs::write(out, text).map_err(|error| format!("cannot write {}: {error}", out.display()))
}

#[cfg(test)]
mod tests {
    #[test]
    fn offline_help_has_the_same_keys_and_examples_as_the_served_registry() {
        let rows = super::data().unwrap_or_else(|error| panic!("{error}"));
        let rows = rows
            .as_array()
            .unwrap_or_else(|| panic!("registry must be a list"));
        let defs = orch_settings_contract::registry::all();
        assert_eq!(rows.len(), defs.len());
        for (row, def) in rows.iter().zip(defs) {
            assert_eq!(row["key"], def.key);
            assert_eq!(
                row["example"],
                def.example_value()
                    .unwrap_or_else(|error| panic!("{error}"))
            );
            assert_eq!(row["text_key"], format!("day100.builtin.{}", def.key));
        }
    }
}
