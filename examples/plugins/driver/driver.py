#!/usr/bin/env python3
"""An unsandboxed Linux process driver over Orch's JSON-lines plugin transport.

Only this driver's --base directory and process groups it started are managed.
Use a dedicated account and a disposable base for conformance checks.
"""

import argparse
import datetime
import json
import os
from pathlib import Path
import re
import shutil
import signal
import subprocess
import sys
import time

VERSION = "0.1.0"
TRANSPORT = 1
CONTRACT = 1
# Polling is only for a process to finish after SIGTERM; twenty checks a second
# avoids a busy loop while keeping stop responsive.
POLL_SECONDS = 0.05
# Names are generated by Orch; restricting them to one path component also
# protects the example's state/volume directories from escaping its base.
NAME = re.compile(r"[a-zA-Z0-9][a-zA-Z0-9_.-]*\Z")
METHODS = ["describe", "validate", "create", "start", "stop", "remove", "inspect",
           "list", "ensure_volume", "remove_volume"]
DESCRIPTOR = {
    "name": "processes", "version": VERSION, "title": "Local process groups",
    "spec_schemas": {kind: {"type": "object", "properties": {
        "command": {"type": "array", "items": {"type": "string"}, "minItems": 1}},
        "additionalProperties": False} for kind in ["environment", "provider"]},
    "confinement": "none", "network_egress": ["open"], "recreate": "restart",
    "volumes": True, "mounts": "none", "private_views": False, "storages": False,
    "suspend": False, "sources": [], "imports": [],
    "resource_limits": {key: "none" for key in ["cpu", "memory", "pids", "disk"]},
    "process_scope": "started", "x_platforms": ["linux"],
}


class Refusal(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code
        self.message = message


def named(value):
    if not isinstance(value, str) or not NAME.fullmatch(value) or value in [".", ".."]:
        raise Refusal("invalid_spec", "a unit or volume name must be one safe path component")
    return value


def now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


class Driver:
    def __init__(self, base, wrong_reply=False):
        self.base = Path(base).resolve()
        self.units = self.base / "units"
        self.volumes = self.base / "volumes"
        self.units.mkdir(parents=True, exist_ok=True)
        self.volumes.mkdir(parents=True, exist_ok=True)
        self.children = {}
        self.wrong_reply = wrong_reply

    def path(self, name):
        return self.units / named(name)

    def record(self, unit):
        path = self.path(unit["name"]) / "unit.json"
        if not path.is_file():
            raise Refusal("not_found", "the unit is absent")
        record = json.loads(path.read_text(encoding="utf-8"))
        if record["unit"] != unit:
            raise Refusal("not_found", "the unit identity differs from the saved unit")
        return record

    def save(self, record):
        path = self.path(record["unit"]["name"])
        temporary = path / "unit.json.next"
        temporary.write_text(json.dumps(record), encoding="utf-8")
        temporary.chmod(0o600)
        temporary.replace(path / "unit.json")

    def validate(self, params):
        spec = params.get("spec") or {}
        command = spec.get("command", ["orch-connector", "run", "--managed"])
        if not isinstance(command, list) or not command or not all(isinstance(arg, str) and arg for arg in command):
            raise Refusal("invalid_spec", "command must contain nonempty arguments")
        if set(spec) - {"command"}:
            raise Refusal("invalid_spec", "this driver accepts only command in its spec")
        return {}

    def create(self, request):
        self.validate({"spec": request["spec"]})
        if request.get("mounts") or request.get("tools"):
            raise Refusal("unsupported", "this example attaches no mounts and installs no harness builds")
        if request.get("network_policy", {}).get("mode", "open") != "open":
            raise Refusal("unsupported", "this process driver cannot restrict the network")
        name = named(request["name"])
        path = self.path(name)
        unit = {"reference": name, "name": name, "runtime_id": request["runtime_id"], "kind": request["kind"]}
        if self.wrong_reply:
            unit["runtime_id"] = "00000000-0000-0000-0000-000000000000"
        if (path / "unit.json").is_file():
            self.record(unit)
            return unit
        path.mkdir(parents=True, exist_ok=True)
        self.save({"unit": unit, "request": request, "pid": None, "pid_start": None,
                   "started_at": None, "finished_at": None, "exit_code": None})
        return unit

    def ensure_volume(self, request):
        if request.get("storage") is not None:
            raise Refusal("unsupported", "this driver has only its default storage")
        (self.volumes / named(request["name"])).mkdir(exist_ok=True)
        return {}

    @staticmethod
    def process_start(pid):
        try:
            # Linux start ticks identify the process, so a reused PID is never
            # signalled as if it were this driver's child. The command field
            # may contain spaces or parentheses; split after its final ')'.
            fields = Path("/proc/%s/stat" % pid).read_text().rsplit(")", 1)[1].split()
            return None if fields[0] == "Z" else fields[19]
        except (OSError, IndexError):
            return None

    def alive(self, record):
        pid = record["pid"]
        child = self.children.get(record["unit"]["name"])
        if child is not None and child.poll() is not None:
            record["exit_code"] = child.returncode
            return False
        return pid is not None and self.process_start(pid) == record.get("pid_start") and record.get("pid_start") is not None

    def start(self, params):
        record = self.record(params["unit"])
        if self.alive(record):
            return {}
        request = record["request"]
        path = self.path(record["unit"]["name"])
        env = dict(os.environ)
        env.update(request.get("env") or {})
        env["ORCH_ROLES"] = ",".join(request["roles"])
        env["ORCH_GATEWAY_URL"] = request["gateway_url"]
        for role, variable in [("state", "ORCH_DATA_DIR"), ("workspace", "ORCH_WORKSPACE_DIR"), ("home", "ORCH_HOME_DIR")]:
            volume = request["volumes"].get(role)
            if volume:
                self.ensure_volume(volume)
                env[variable] = str(self.volumes / named(volume["name"]))
        for filename, variable, value in [("ca.pem", "ORCH_CA_FILE", request["ca_cert"]),
                                           ("enroll", "ORCH_ENROLL_FILE", request["enroll_token"]),
                                           ("mounts.json", "ORCH_MOUNTS_FILE", "[]")]:
            file = path / filename
            file.write_text(value, encoding="utf-8")
            file.chmod(0o600)
            env[variable] = str(file)
        tools = path / "tools"
        tools.mkdir(exist_ok=True)
        tools.chmod(0o555)
        env["ORCH_TOOLS_DIR"] = str(tools)
        command = request["spec"].get("command", ["orch-connector", "run", "--managed"])
        with (path / "process.log").open("ab") as log:
            child = subprocess.Popen(command, cwd=env.get("ORCH_WORKSPACE_DIR", path), env=env,
                                     stdin=subprocess.DEVNULL, stdout=log, stderr=log, start_new_session=True)
        self.children[record["unit"]["name"]] = child
        record.update(pid=child.pid, pid_start=self.process_start(child.pid), started_at=now(), finished_at=None, exit_code=None)
        self.save(record)
        return {}

    def stop(self, params):
        record = self.record(params["unit"])
        if self.alive(record):
            os.killpg(record["pid"], signal.SIGTERM)
            deadline = time.monotonic() + max(0, params.get("grace_secs", 0))
            while self.alive(record) and time.monotonic() < deadline:
                time.sleep(POLL_SECONDS)
            if self.alive(record):
                os.killpg(record["pid"], signal.SIGKILL)
        child = self.children.pop(record["unit"]["name"], None)
        if child is not None:
            record["exit_code"] = child.wait()
        record.update(pid=None, pid_start=None, finished_at=now())
        self.save(record)
        return {}

    def inspect(self, params):
        try:
            record = self.record(params["unit"])
        except Refusal as error:
            if error.code != "not_found":
                raise
            return {"state": "absent", "detail": None, "exit_code": None, "started_at": None, "finished_at": None}
        running = self.alive(record)
        return {"state": "running" if running else "stopped", "detail": None,
                "exit_code": record["exit_code"], "started_at": record["started_at"], "finished_at": record["finished_at"]}

    def remove(self, params):
        path = self.path(params["unit"]["name"])
        if not (path / "unit.json").exists():
            return {}
        self.stop({"unit": params["unit"], "grace_secs": 0})
        (path / "tools").chmod(0o755) if (path / "tools").exists() else None
        shutil.rmtree(path)
        return {}

    def remove_volume(self, params):
        path = self.volumes / named(params["name"])
        if path.exists():
            shutil.rmtree(path)
        return {}

    def list(self, params):
        units = []
        for path in self.units.glob("*/unit.json"):
            record = json.loads(path.read_text(encoding="utf-8"))
            if record["request"].get("labels", {}).get("orch.system") == params["system"]:
                units.append(record["unit"])
        return {"units": units}


def hello(params):
    offered = params.get("contract") or (params.get("contracts") or {}).get("driver")
    if offered is None or not params["transport"][0] <= TRANSPORT <= params["transport"][1] or not offered[0] <= CONTRACT <= offered[1]:
        raise Refusal("unsupported_version", "this example speaks transport 1 and driver contract 1")
    return {"kind": "driver", "transport": TRANSPORT, "contract": CONTRACT,
            "name": "processes", "version": VERSION, "methods": METHODS, "descriptor": DESCRIPTOR}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", required=True, help="directory reserved for this driver's units and volumes")
    parser.add_argument("--wrong-reply", action="store_true", help="return another runtime id to deliberately fail driver.create")
    args = parser.parse_args()
    if not sys.platform.startswith("linux"):
        parser.error("this process example supports Linux only")
    driver = Driver(args.base, args.wrong_reply)
    methods = {name: getattr(driver, name) for name in METHODS if name != "describe"}
    methods.update(describe=lambda _: DESCRIPTOR, ping=lambda _: {})
    for line in sys.stdin:
        request = json.loads(line)
        name = request.get("method")
        if "id" not in request:
            if name == "shutdown":
                return
            continue
        try:
            if name == "hello":
                result = hello(request.get("params") or {})
            elif name in methods:
                result = methods[name](request.get("params") or {})
            else:
                raise Refusal("unsupported", "unknown method")
            reply = {"id": request["id"], "result": result}
        except Refusal as error:
            reply = {"id": request["id"], "error": {"code": error.code, "message": error.message, "retryable": False}}
        except (OSError, KeyError, ValueError) as error:
            print("driver request failed: %s" % type(error).__name__, file=sys.stderr)
            reply = {"id": request["id"], "error": {"code": "internal", "message": "the process operation failed", "retryable": False}}
        print(json.dumps(reply), flush=True)


if __name__ == "__main__":
    main()
